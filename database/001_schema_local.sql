-- Esquema PostgreSQL aislado para validar la migración de Ganjah Team.
-- No ejecutar sobre Supabase: recrea las tres tablas del entorno local.
begin;

drop table if exists matchday_jugadores;
drop table if exists matchday;
drop table if exists jugadores;

create table jugadores (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    posicion varchar(40) not null,
    nivel_ataque smallint not null check (nivel_ataque between 1 and 5),
    nivel_defensa smallint not null check (nivel_defensa between 1 and 5)
);

create unique index uq_jugadores_nombre_normalizado
    on jugadores (lower(btrim(nombre)));

create table matchday (
    id bigint generated by default as identity primary key,
    fecha_partido timestamp not null,
    goles_local smallint null check (goles_local >= 0),
    goles_visitante smallint null check (goles_visitante >= 0),
    constraint ck_marcador_completo check (
        (goles_local is null and goles_visitante is null)
        or (goles_local is not null and goles_visitante is not null)
    )
);

create table matchday_jugadores (
    participacion_id bigint generated always as identity primary key,
    matchday_id bigint not null references matchday(id) on delete cascade,
    jugador_id bigint null references jugadores(id) on delete set null,
    nombre_jugador varchar(120) not null,
    equipo varchar(10) null check (equipo in ('LOCAL', 'VISITANTE')),
    constraint uq_matchday_nombre unique (matchday_id, nombre_jugador)
);

create index ix_matchday_jugadores_matchday on matchday_jugadores(matchday_id);
create index ix_matchday_jugadores_jugador on matchday_jugadores(jugador_id);
create index ix_matchday_fecha on matchday(fecha_partido desc);

commit;
