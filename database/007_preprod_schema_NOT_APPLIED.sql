-- ESQUEMA PARA UNA BASE PREVIEW NUEVA E INDEPENDIENTE.
-- NO ejecutar sobre el Supabase histórico ni sobre una base con datos reales.
\set ON_ERROR_STOP on

begin;

create table if not exists jugadores (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    posicion varchar(40) not null,
    nivel_ataque integer not null check (nivel_ataque between 1 and 5),
    nivel_defensa integer not null check (nivel_defensa between 1 and 5)
);
create unique index if not exists uq_jugadores_nombre_normalizado
    on jugadores (lower(btrim(nombre)));

create table if not exists matchday (
    id bigint generated by default as identity primary key,
    fecha_partido timestamp not null,
    goles_local integer null check (goles_local >= 0),
    goles_visitante integer null check (goles_visitante >= 0),
    constraint ck_marcador_completo check (
        (goles_local is null and goles_visitante is null)
        or (goles_local is not null and goles_visitante is not null)
    )
);
create index if not exists ix_matchday_fecha on matchday(fecha_partido desc);

create table if not exists matchday_jugadores (
    participacion_id bigint generated always as identity primary key,
    matchday_id bigint not null references matchday(id) on delete cascade,
    jugador_id bigint null references jugadores(id) on delete set null,
    nombre_jugador varchar(120) not null,
    equipo varchar(10) null check (equipo in ('LOCAL', 'VISITANTE')),
    constraint uq_matchday_nombre unique (matchday_id, nombre_jugador)
);
create index if not exists ix_matchday_jugadores_matchday
    on matchday_jugadores(matchday_id);
create index if not exists ix_matchday_jugadores_jugador
    on matchday_jugadores(jugador_id);

create table if not exists auth_sessions (
    session_id varchar(64) primary key,
    username varchar(80) not null,
    expires_at timestamptz not null
);
create index if not exists auth_sessions_expires_at_idx
    on auth_sessions(expires_at);

create table if not exists login_attempts (
    fingerprint varchar(64) primary key,
    window_started_at timestamptz not null,
    failure_count integer not null check (failure_count >= 0),
    locked_until timestamptz null
);

commit;
